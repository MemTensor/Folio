const assert = require('node:assert/strict');
async function verifyDocumentLifecycle(window, controls) {
  const { file, referenceFile, researchFile, language } = controls;
  const evaluate = (fn, ...args) =>
    window.webContents.executeJavaScript(
      '(' + fn + ')(' + args.map(JSON.stringify).join(',') + ')',
    );
  const wait = async (check) => {
    for (let i = 0; i < 120; i++) {
      if (await check()) return;
      await new Promise((resolve) => setTimeout(resolve, 25));
    }
    throw Error('Document lifecycle did not reach the expected state.');
  };
  const active = (path) =>
    evaluate((p) => document.querySelector('.document-surface')?.dataset.documentPath === p, path);
  const select = async (p) => {
    await evaluate(
      (path) => [...document.querySelectorAll('.doc-tab')].find((b) => b.title === path).click(),
      p,
    );
    await wait(() => active(p));
  };
  // Disable autosave in this generated fixture. Recovery drafts still run.
  await evaluate(() =>
    localStorage.setItem(
      'folio-preferences',
      JSON.stringify({
        ...JSON.parse(localStorage.getItem('folio-preferences') || '{}'),
        autoSave: false,
      }),
    ),
  );
  await window.loadURL('folio://app/index.html');
  await wait(() => active(file));
  controls.holdResearch();
  window.webContents.send('command', 'home');
  await wait(() => evaluate(() => !!document.querySelector('.project-home')));
  await evaluate(() =>
    [...document.querySelectorAll('.recent-document')]
      .find((b) => b.textContent.includes('Research'))
      .click(),
  );
  await wait(() => controls.researchStarted());
  await evaluate(
    (english) =>
      [...document.querySelectorAll('.project-home button')]
        .find((b) => b.textContent.trim() === (english ? 'Back to document' : '返回文档'))
        .click(),
    language === 'en',
  );
  await wait(controls.nativeRestored);
  controls.releaseResearch();
  await new Promise((resolve) => setTimeout(resolve, 100));
  assert(await active(file), 'Canceled recent document must not become active.');
  window.webContents.send('open-request', {
    root: require('node:path').dirname(file),
    path: referenceFile,
  });
  await wait(() => active(referenceFile));
  await select(file);
  await evaluate(
    (english) =>
      [...document.querySelectorAll('.view-switch button')]
        .find((b) => b.textContent === (english ? 'Source' : '源码'))
        .click(),
    language === 'en',
  );
  await evaluate(() => {
    const input = document.querySelector('input[type=file]'),
      data = new DataTransfer();
    data.items.add(new File(['generated image bytes'], 'generated.png', { type: 'image/png' }));
    input.files = data.files;
    input.dispatchEvent(new Event('change', { bubbles: true }));
  });
  await wait(controls.imageStarted);
  await select(referenceFile);
  controls.releaseImage();
  await wait(() => evaluate(() => !!document.querySelector('.image-import-recovery')));
  assert.equal(
    await evaluate(() =>
      document.querySelector('.cm-content')?.textContent.includes('assets/generated.png'),
    ),
    false,
  );
  await wait(() => evaluate(() => !!localStorage.getItem('folio-image-import-recovery')));
  await window.loadURL('folio://app/index.html');
  await wait(() =>
    evaluate(
      () =>
        !!document.querySelector('.image-import-recovery') &&
        !!document.querySelector('.view-switch'),
    ),
  );
  await evaluate(
    (english) =>
      [...document.querySelectorAll('.view-switch button')]
        .find((b) => b.textContent === (english ? 'Source' : '源码'))
        .click(),
    language === 'en',
  );
  const append = async () => {
    await evaluate(
      (english) =>
        [...document.querySelectorAll('.image-import-recovery button')]
          .find(
            (b) => b.textContent === (english ? 'Append to original document' : '插入原文档末尾'),
          )
          .click(),
      language === 'en',
    );
    await wait(() => evaluate(() => !document.querySelector('.image-import-recovery')));
    await wait(() => active(file));
  };
  await append();
  assert(controls.draft(file)?.content.includes('assets/generated.png'));
  assert(
    await evaluate(() =>
      document.querySelector('.cm-content')?.textContent.includes('assets/generated.png'),
    ),
  );
  const importFiles = async (names) => {
    await evaluate((files) => {
      const input = document.querySelector('input[type=file]'),
        data = new DataTransfer();
      for (const name of files)
        data.items.add(new File(['generated bytes'], name, { type: 'image/png' }));
      input.files = data.files;
      input.dispatchEvent(new Event('change', { bubbles: true }));
    }, names);
  };
  controls.configureImages('hold-second');
  await importFiles(['batch-one.png', 'batch-two.png', 'batch-three.png']);
  await wait(controls.imageStarted);
  await select(referenceFile);
  controls.releaseImage();
  await wait(() => evaluate(() => !!document.querySelector('.image-import-recovery')));
  const recovered = await evaluate(() =>
    JSON.parse(localStorage.getItem('folio-image-import-recovery')),
  );
  assert.equal(recovered.path, file);
  assert.deepEqual(
    recovered.items.map((item) => item.relative),
    ['assets/batch-one.png', 'assets/batch-two.png'],
  );
  assert.equal(controls.imageCalls(), 2);
  assert.equal(
    await evaluate(() =>
      document.querySelector('.cm-content')?.textContent.includes('assets/batch-one.png'),
    ),
    false,
  );
  await append();
  assert(controls.draft(file)?.content.includes('assets/batch-one.png'));
  assert(controls.draft(file)?.content.includes('assets/batch-two.png'));
  controls.configureImages('fail-second');
  await importFiles(['success.png', 'failed.png']);
  await wait(() =>
    evaluate(() =>
      document.querySelector('.cm-content')?.textContent.includes('assets/success.png'),
    ),
  );
  assert.equal(controls.imageCalls(), 2);
  assert(await evaluate(() => !!document.querySelector('.error-banner')));
  assert.equal(await evaluate(() => !!document.querySelector('.image-import-recovery')), false);
  // Open the third tab explicitly: the canceled open must not have created it.
  window.webContents.send('command', 'home');
  await wait(() => evaluate(() => !!document.querySelector('.project-home')));
  await evaluate(() =>
    [...document.querySelectorAll('.recent-document')]
      .find((b) => b.textContent.includes('Research'))
      .click(),
  );
  await wait(() => active(researchFile));
  controls.contextAction('close-others');
  await evaluate(
    (path) =>
      [...document.querySelectorAll('.doc-tab')]
        .find((b) => b.title === path)
        .dispatchEvent(
          new MouseEvent('contextmenu', { bubbles: true, cancelable: true, button: 2 }),
        ),
    file,
  );
  await wait(() => evaluate(() => document.querySelectorAll('.doc-tab').length === 1));
  assert(await active(file));
  assert.equal(await evaluate(() => document.querySelectorAll('.doc-tab.active').length), 1);
  return {
    canceledOpen: true,
    imageTargetProtected: true,
    multiImageRecovery: true,
    importRecoveryAfterRestart: true,
    partialCopyPreserved: true,
    remainingTabActive: true,
  };
}
module.exports = { verifyDocumentLifecycle };
